/* =========================
   CHAPTER SELECT
========================= */

function createChapterSelect() {

    chapterSelect.innerHTML = "";

    chapters.forEach(function(chapter, index) {

        const option =
            document.createElement("option");

        option.value = chapter.start;

        option.textContent =
            chapter.name;

        chapterSelect.appendChild(option);

    });
}


function updateSelect() {

    let selectedChapter = 0;

    chapters.forEach(function(chapter, index) {

        if (
            currentPage >= chapter.start &&
            currentPage <= chapter.end
        ) {
            selectedChapter = index;
        }

    });

    chapterSelect.selectedIndex =
        selectedChapter;
}


chapterSelect.addEventListener(
    "change",
    function() {

        const page =
            Number(this.value);

        loadBookPage(page);

    }
);



/* =========================
   CHAPTER LIST
========================= */

function createChapterList() {

    chapterList.innerHTML = "";

    chapters.forEach(function(chapter, index) {

        const item =
            document.createElement("div");

        item.className =
            "chapter-list-item";

        const number =
            String(index + 1).padStart(2, "0");

        item.innerHTML = `
            <small>${number}</small>
            <strong>${chapter.name}</strong>
            <span>
                ${
                    chapter.start === 0
                        ? "Prologue"
                        : "Pages " +
                          chapter.start +
                          "–" +
                          chapter.end
                }
            </span>
        `;

        item.addEventListener(
            "click",
            function() {

                loadBookPage(
                    chapter.start
                );

            }
        );

        chapterList.appendChild(item);

    });
}



