/* =========================
   LOAD PAGE
========================= */

function loadBookPage(index) {

    if (index < 0) {
        index = 0;
    }

    if (index >= bookPages.length) {
        index = bookPages.length - 1;
    }

    currentPage = index;

    const page = bookPages[currentPage];

    storyChapter.textContent = page.chapter;
    storyTitle.textContent = page.title;
    storyPageNumber.textContent = page.page;

    storyText.innerHTML = "";

    page.text.forEach(function(paragraph) {

        const p = document.createElement("p");

        p.textContent = paragraph;

        if (
            paragraph === "Some summers end with the season." ||
            paragraph === "Some stay with you." ||
            paragraph === "Some summers end." ||
            paragraph === "Some summers stay forever." ||
            paragraph === "Distance doesn't always begin with leaving."
        ) {
            p.className = "special-line";
        }

        storyText.appendChild(p);

    });


    updateProgress();
    updateButtons();
    updateSelect();

    window.scrollTo({
        top: document.querySelector(".story-page").offsetTop - 100,
        behavior: "smooth"
    });
}



/* =========================
   PROGRESS
========================= */

function updateProgress() {

    const percentage =
        ((currentPage + 1) / bookPages.length) * 100;

    progressFill.style.width =
        percentage.toFixed(1) + "%";

    progressText.textContent =
        Math.round(percentage) + "%";

    pageCounter.textContent =
        currentPage === 0
            ? "Prologue"
            : "Page " + (currentPage);

    chapterProgress.textContent =
        bookPages[currentPage].chapter +
        " • " +
        bookPages[currentPage].title;
}



/* =========================
   BUTTONS
========================= */

function updateButtons() {

    previousBtn.disabled =
        currentPage === 0;

    nextBtn.disabled =
        currentPage === bookPages.length - 1;
}


previousBtn.addEventListener(
    "click",
    function() {

        if (currentPage > 0) {
            loadBookPage(currentPage - 1);
        }

    }
);


nextBtn.addEventListener(
    "click",
    function() {

        if (currentPage < bookPages.length - 1) {
            loadBookPage(currentPage + 1);
        }

    }
);



